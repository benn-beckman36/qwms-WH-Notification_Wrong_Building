        private void btnConfirm_Click(object sender, System.EventArgs e)
        {
            try
            {
                stsWarning.Text = "";
                if (txtMBLNR.Text.Trim() != "")
                {
                    string[] aryTempMblnr;
                    aryTempMblnr = txtMBLNR.Text.Trim().Split(new char[] { ',' });
                    aryMblnr.Clear();
                    if (aryMblnr.Count == 0)
                    {
                        for (int i = 0; i < aryTempMblnr.Length; i++)
                        {
                            aryMblnr.Add(aryTempMblnr[i].ToString().Trim());
                        }
                    }
                }

                if (cmbWerks.SelectedIndex != -1)
                    strWerks = cmbWerks.Items[cmbWerks.SelectedIndex].ToString();
                else
                    strWerks = "";

                if (cmbLgort.SelectedIndex != -1)
                    strLgort = cmbLgort.Items[cmbLgort.SelectedIndex].ToString();
                else
                    strLgort = "";
                //廠區倉別不為空
                if (Werks == "" || Lgort == "")
                {
                    stsWarning.Text = "Plant and storage can't be empty!!";
                    return;
                }
                //库位
                if (txtLocat.Text.Trim() == "")
                {
                    stsWarning.Text = "Location can't be empty！!!";
                    return;
                }
                //单号不为空
                if (Mblnr.Count == 0)
                {
                    stsWarning.Text = "Document No can't be empty!!";
                    return;
                }

                if (Mblnr.Count > 1)
                {
                    stsWarning.Text = "一次只能选择一条单据";
                    return;
                }
                QCI.QWMS.StorageIn objStorageIn = new QCI.QWMS.StorageIn(CommonInfo.Instance.DBType, CommonInfo.Instance.DBCode.ToString(), CommonInfo.Instance.ErrType, CommonInfo.Instance.ErrCode.ToString(), UserData, Werks, Lgort, "", Progid);

                //EC单号
                dtVBELN = objStorageIn.QuerySAPByECNo(txtMBLNR.Text.Trim());
                if (dtVBELN == null || dtVBELN.Rows.Count == 0)
                {
                    stsWarning.Text = "EC单扣帐单号暂未回传，请稍候重试!!";
                    return;
                }
                //同一EC单相关的SAP单据
                dtStorageIn = objStorageIn.QuerySAPInData(Locat, dtpIndat.Value.ToString("yyyyMMdd"),
                                                          dtVBELN.Rows[0]["BWART"].ToString(), dtVBELN.Rows[0]["VBELN"].ToString(),
                                                          dtVBELN.Rows[0]["MATNR"].ToString(), dtVBELN.Rows[0]["CHARG"].ToString());
                if (dtStorageIn.Rows.Count == 0)
                {
                    stsWarning.Text = "No data!!";
                    return;
                }

                #region 扣帐单号信息
                foreach (DataRow tmpRow in dtStorageIn.Rows)
                {
                    strInsmk = tmpRow["INSMK"].ToString();
                    intTotalAlqty += Convert.ToInt32(tmpRow["MENGE"].ToString());
                }
                #endregion
                
                ShowInSourceDataGrid();
                


                #region 設定按鈕状态
                this.btnConfirm.Enabled = false;
                this.cmbWerks.Enabled = false;
                this.cmbLgort.Enabled = false;
                this.txtLocat.Enabled = false;
                this.txtMBLNR.Enabled = false;
                this.txtBoxID.Text = "";
                this.txtBoxID.Enabled = true;
                txtBoxID.Focus();
                this.txtScannedQty.Enabled = false;
                this.txtSanLocation.Enabled = true;
                rdoNew.Enabled = false;
                rdoAdd.Enabled = false;
                //txtLoCod.Enabled = true;
                #endregion

            }
            catch (Exception ex)
            {
                stsWarning.Text = ex.Message;
                return;
            }
        }

