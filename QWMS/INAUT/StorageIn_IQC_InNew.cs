        #region txtBoxID_KeyDown
        private void txtBoxID_KeyDown(object sender, System.Windows.Forms.KeyEventArgs e)
        {

            #region 變數宣告
            stsWarning.Text = string.Empty;
            DataTable dtTemp = new DataTable();
            QCI.QWMS.SapData objSapData = new QCI.QWMS.SapData(CommonInfo.Instance.DBType, CommonInfo.Instance.DBCode.ToString(), CommonInfo.Instance.ErrType, CommonInfo.Instance.ErrCode.ToString(), UserData, cmbWerks.Text.Trim(), Lgort);
            string strECNo = "";
            string strMatnr = "";
            #endregion

            if (e.KeyCode == System.Windows.Forms.Keys.Enter)
            {
                try
                {
                    QCI.QWMS.StorageIn objStorageIn = new QCI.QWMS.StorageIn(CommonInfo.Instance.DBType, CommonInfo.Instance.DBCode.ToString(), CommonInfo.Instance.ErrType, CommonInfo.Instance.ErrCode.ToString(), UserData, Werks, Lgort, "", Progid);
                    DataTable dtbox = new DataTable();

                    #region Valid Code

                    #region BOXID 存在性

                    string strBoxID = txtBoxID.Text.Trim().ToUpper();
                    if (string.IsNullOrEmpty(strBoxID))
                    {
                        throw new Exception("Box ID 不能为空!!");
                    }

                    #endregion

                    #region ECBOX 数据存在性

                    //ECBOX
                    dtbox = objStorageIn.QueryECBox(Werks,Lgort,txtBoxID.Text.Trim().ToUpper());
                    if (dtbox.Rows.Count > 0)
                    {
                        strECNo = dtbox.Rows[0]["VBELN"].ToString().Trim();
                        strMatnr = dtbox.Rows[0]["MATNR"].ToString().Trim();
                        if (dtbox.Rows[0]["FLAGE"].ToString().Trim() == "Y")
                        {
                            Sound.Play(@"Sound\ERROR.wav");
                            throw new Exception("BOX ID：" + txtBoxID.Text.Trim() + "已入库!!");
                        }
                        ShowDdlLgort(dtbox.Rows[0]["LGORT"].ToString().Trim());
                    }
                    else
                    {
                        Sound.Play(@"Sound\ERROR.wav");
                        throw new Exception("无BOX资料!!");
                    }

                    #endregion

                    #region Plant/Storage 存在性

                    //Plant/Storage不允许为空
                    strWerks = Convert.ToString(cmbWerks.Items[cmbWerks.SelectedIndex]);
                    strLgort = Convert.ToString(cmbLgort.Items[cmbLgort.SelectedIndex]);

                    if (string.IsNullOrEmpty(Werks) || string.IsNullOrEmpty(Lgort))
                    {
                        throw new Exception("Plant 和 storage 不能为空!!");
                    }

                    //Storage必须有数据
                    QCI.QWMS.PlantData objPlantData = new QCI.QWMS.PlantData(UserData);
                    dtTemp = objPlantData.GetPlantStorageData("LGORT", strWerks, strLgort);
                    if (dtTemp.Rows.Count >= 1)
                    {
                        strSttyp = dtTemp.Rows[0]["CTRLC4"].ToString().ToUpper();
                        strLotyp = dtTemp.Rows[0]["CTRLC5"].ToString().ToUpper();
                    }
                    else
                    {
                        throw new Exception("没有 storage 数据!!");
                    }

                    #endregion

                    #region ECInfo

                    if (strECNo.ToUpper() != dtVBELN.Rows[0]["VBELN"].ToString().ToUpper())
                    {
                        Sound.Play(@"sound\error.wav");
                        throw new Exception("扫入的BOX与扣帐单号不匹配!!");
                    }
                    if (strMatnr.ToUpper() != dtVBELN.Rows[0]["MATNR"].ToString().ToUpper())
                    {
                        Sound.Play(@"sound\error.wav");
                        throw new Exception("扫入的料号与扣帐单号不匹配!!");
                    }
                    #endregion

                    #region DataGridView 初始化

                    if (Data.Rows.Count == 0)
                    {
                        dtTmpData = new DataTable();
                        //ECBOX Data
                        dtTmpData = objStorageIn.QueryECBoxByECNo(Werks, Lgort, txtLocat.Text.Trim(), dtpIndat.Value.ToString("yyyyMMdd"), strECNo, Insmk, strMatnr);

                        if (dtTmpData != null && dtTmpData.Rows.Count > 0)
                        {
                            //初始化 DataTable
                            GetDefaultTable();
                            //填值到DataTable
                            SetDefaultValue(dtTmpData);

                            ShowDataGrid();
                        }
                        else
                        {
                            txtBoxID.Text = string.Empty;
                            Sound.Play(@"Sound\ERROR.wav");
                            throw new Exception("无数据!!");
                        }
                    }

                    #endregion

                    #region 单笔BOXID是否已经刷入/是否存在
                    int tempQty = 0;
                    foreach (DataGridViewRow dataGridRow in dgvData.Rows)
                    {
                        dataGridRow.DefaultCellStyle.BackColor = Color.Silver;
                        if (txtBoxID.Text.Trim().ToUpper() == dataGridRow.Cells[2].Value.ToString().ToUpper())
                        {

                            if (dataGridRow.Cells[0].Value.ToString() == "True")
                            {
                                Sound.Play(@"Sound\ERROR.wav");
                                throw new Exception("BOX ID 已经扫过!!");
                            }
                            else
                            {
                                tempQty += Int32.Parse(dataGridRow.Cells[4].Value.ToString());
                                if (intTotalAlqty >= tempQty)
                                {
                                    #region 修改入库单据数量
                                    //本次待入库数量
                                    int intNowInQty = tempQty;
                                    foreach (DataRow dr in dtStorageIn.Rows)
                                    {
                                        if (intNowInQty == 0) 
                                            break;

                                        if (dr["MENGE"].ToString() != dr["ALQTY"].ToString())
                                        {
                                            //可入库数量
                                            int intCanStorageInQty = Convert.ToInt32(dr["MENGE"].ToString()) - Convert.ToInt32(dr["ALQTY"].ToString());
                                            if (intCanStorageInQty > 0)
                                            {
                                                //WHLOG异动记录
                                                if (dtCombineData.Rows.Count == 0)
                                                    GetCombineDataTable();

                                                DataRow drRow = dtCombineData.NewRow();

                                                drRow["MANDT"] = Mandt;
                                                drRow["COMCD"] = Comcd;
                                                drRow["WERKS"] = dr["WERKS"].ToString();
                                                drRow["LGORT"] = dr["LGORT"].ToString();
                                                drRow["LOCAT"] = txtLocat.Text.Trim();
                                                drRow["MBLNR"] = dr["MBLNR"].ToString();
                                                drRow["BOXID"] = dataGridRow.Cells[2].Value.ToString().ToUpper();
                                                drRow["MATNR"] = dr["MATNR"].ToString();
                                                drRow["INSMK"] = dr["INSMK"].ToString();
                                                
                                                if (intNowInQty > intCanStorageInQty)
                                                {
                                                    drRow["ALGQTY"] = intCanStorageInQty;
                                                    dr["ALQTY"] = Convert.ToInt32(dr["ALQTY"].ToString()) + intCanStorageInQty;
                                                    intNowInQty = intNowInQty - intCanStorageInQty;
                                                }
                                                else
                                                {
                                                    drRow["ALGQTY"] = intNowInQty;
                                                    dr["ALQTY"] = Convert.ToInt32(dr["ALQTY"].ToString()) + intNowInQty;
                                                    intNowInQty = 0;
                                                }

                                                dtCombineData.Rows.Add(drRow);
                                            }
                                        }
                                    }
                                    #endregion

                                    intTotalAlqty = intTotalAlqty - tempQty;
                                    dataGridRow.Cells[0].Value = true;
                                    dataGridRow.DefaultCellStyle.BackColor = Color.Blue;
                                }
                                else
                                {
                                    Sound.Play(@"Sound\ERROR.wav");
                                    throw new Exception("SAP单据数量不足!!");
                                }
                            }
                        }
                    }

                    if (tempQty == 0)
                    {
                        throw new Exception("Box ID 不存在!!!");
                    }
                    else
                    {
                        intScanQty += tempQty;
                    }
                    txtScannedQty.Text = intScanQty.ToString();

                    #endregion

                    DataRow[] drScan = Data.Select("CHKED = true");
                    lblDataCount.Text = string.Format("Scanned {0} of {1} records", drScan.Length, Data.Rows.Count.ToString());
                    if (intTotalAlqty == 0)
                    {
                        if (strType == "ADD")
                        {
                            this.txtSanLocation.Focus();
                        }
                    }
                    else
                    {
                        btnSave.Enabled = false;
                    }

                    #endregion
                }
                catch (Exception ex)
                {
                    stsWarning.Text = ex.Message;
                    this.txtBoxID.Text = "";
                    Sound.Play(@"Sound\ERROR.wav");
                    return;
                }
                finally
                {
                    this.txtBoxID.Text = string.Empty;
                }
            }
        }
